// =====================================================
//  scripts/gen-secret.js
//  Ажиллуулах:  npm run gen-secret
//
//  Санамсаргүй түлхүүр болон нууц үг үүсгэнэ.
//  Гараар бодож олсон мөр хэзээ ч хангалттай санамсаргүй байдаггүй.
// =====================================================

const crypto = require('crypto');

const secret = crypto.randomBytes(48).toString('base64url');
const dbPass = crypto.randomBytes(18).toString('base64url');

console.log(`
  Доорхыг server/.env файлдаа хуулна уу.
  ────────────────────────────────────────────────────

  JWT_SECRET=${secret}

  Өгөгдлийн сангийн хэрэглэгчийн нууц үг (сонголтоор):

  ${dbPass}

  ────────────────────────────────────────────────────
  JWT_SECRET солих үед нэвтэрсэн бүх хэрэглэгч гарна.
  Энэ нь хүлээгдэж буй үр дүн — хуучин токенууд хүчингүй болно.
`);